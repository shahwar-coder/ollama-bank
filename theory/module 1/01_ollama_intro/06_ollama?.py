'''
What is Ollama?

Ollama is a software tool that lets you:

- Download open-source LLMs
- Run them locally
- Use them directly on your own computer

Example models:
- Llama 3
- Mistral
- Gemma

Instead of calling a cloud API (like OpenAI),
Ollama runs the model on your local machine.

Key Features:

1. Works Offline
   - No internet required after model download.

2. No Per-Token Cost
   - No API billing.

3. Full Data Privacy
   - Your data stays on your computer.

4. Simple Interface
   - CLI commands (ollama run, ollama pull)
   - REST API server
   - Python integration

Simple Definition:

Ollama = Local LLM runtime that helps you
download, manage, and run large language models
on your own hardware.

Mental Model:

OpenAI API → Brain lives in cloud.
Ollama → Brain lives on your computer.
'''
