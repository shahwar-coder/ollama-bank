'''
Q1. What is open source in simple terms?
A.
Open source means the source code of a software is publicly available.
Anyone can view it, modify it, use it, and contribute improvements.
It promotes transparency, collaboration, and learning.
'''

# Example:
# Open-source project: Ollama
# You can:
# - Visit its GitHub repo
# - Read how models are loaded
# - Modify behavior
# - Build tools on top of it


'''
Q2. What is closed source software?
A.
Closed source software keeps its source code private.
Only the owning company can view or modify it.
Users can use the software, but cannot see or change how it works internally.
'''

# Example:
# Many proprietary AI APIs
# You can call the API and get results,
# but you cannot see how the model is implemented internally.


'''
Q3. What is the main difference between open source and closed source?
A.
The main difference is access and control.
Open source allows public access and modification of code.
Closed source restricts access and keeps implementation private.
'''

# Example comparison:
# Open source → Transparent kitchen (see recipe)
# Closed source → Secret recipe restaurant (cannot see recipe)


'''
Q4. Why is Ollama considered open source?
A.
Ollama is open source because its source code is publicly available.
Developers can inspect, modify, extend, and contribute to its codebase.
'''

# Example:
# You can:
# - Inspect how Ollama runs models locally
# - Customize configurations
# - Integrate it into custom AI workflows


'''
Q5. Why does open source matter for AI engineers?
A.
Open source allows engineers to deeply understand model serving,
infrastructure, and system design instead of just consuming APIs.
It enables experimentation, learning, and contribution.
'''

# Example:
# With open source tools:
# - Run LLMs locally
# - Modify inference logic
# - Experiment with deployment strategies


'''
Q6. Why might companies choose closed source software?
A.
Companies may choose closed source to protect intellectual property,
control usage, maintain competitive advantage, and manage security risks.
'''

# Example:
# A proprietary LLM API:
# - Company controls updates
# - Users cannot inspect model internals
# - Pricing and access are centrally managed
